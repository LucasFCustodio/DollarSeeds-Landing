  ['easy', 'Easy', '1 blank', 'Pick from 3 words', '1 point per verse'],
  ['medium', 'Medium', '3 blanks', 'Pick from 6 words', '2 points per correct word'],
  ['hard', 'Hard', '3 blanks', 'Type the words', '5 points per correct word']
