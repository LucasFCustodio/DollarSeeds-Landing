'use strict';

/**
 * Seed Rush: the browser assets and the app-like pages.
 *
 *   1. assets/js/vendor/supabase.js   — the Supabase UMD bundle, copied from
 *      node_modules (no CDN: the CSP allows scripts only from this site and Termly)
 *   2. assets/js/seed-rush-config.js — API and Supabase settings, from site.config.js
 *   3. seed-rush/index.html, daily.html, practice.html, verify.html
 *
 * Pages reference the Seed Rush assets with a content-hash query (?v=…), so a
 * changed file reaches returning visitors despite /assets/* being immutable.
 * Steps 1 and 2 run first so the pages hash their final bytes.
 *
 * The Study page and the verse pages come from scripts/gen-verses.js.
 */

const fs = require('fs');
const path = require('path');
const { ROOT, APP, SEED_RUSH, url } = require('./site.config.js');
const shell = require('./seed-rush-shell.js');

const GENERATOR = 'scripts/gen-seed-rush.js';
const changed = [];

function out(rel, body) {
  if (shell.writeIfChanged(rel, body)) changed.push(rel);
}

// ── 1. vendor bundle ────────────────────────────────────────────────────────
function vendor() {
  const src = path.join(ROOT, 'node_modules', '@supabase', 'supabase-js', 'dist', 'umd', 'supabase.js');
  const dest = 'assets/js/vendor/supabase.js';
  if (!fs.existsSync(src)) {
    // A build without node_modules (should not happen on Netlify, which runs
    // npm install first) keeps the committed copy rather than failing.
    if (fs.existsSync(path.join(ROOT, dest))) {
      console.warn('seed-rush: @supabase/supabase-js not installed — keeping the committed vendor bundle');
      return;
    }
    throw new Error('@supabase/supabase-js is not installed and no vendor bundle is committed. Run npm install.');
  }
  const version = require(path.join(ROOT, 'node_modules', '@supabase', 'supabase-js', 'package.json')).version;
  out(dest, '/*! @supabase/supabase-js ' + version + ' (UMD) — copied by ' + GENERATOR + ' */\n' +
    fs.readFileSync(src, 'utf8'));
}

// ── 2. runtime config ───────────────────────────────────────────────────────
function config() {
  const cfg = {
    api: SEED_RUSH.api,
    supabaseUrl: SEED_RUSH.supabaseUrl,
    supabasePublishableKey: SEED_RUSH.supabasePublishableKey,
    supportEmail: SEED_RUSH.supportEmail,
    origin: url('/').slice(0, -1)
  };
  out('assets/js/seed-rush-config.js',
    '/* Generated by ' + GENERATOR + ' from scripts/site.config.js. Do not edit by hand.\n' +
    '   Public values only: the Supabase key is the anon (publishable) client key. */\n' +
    'window.SEED_RUSH_CONFIG = ' + JSON.stringify(cfg, null, 2) + ';\n');
}

// ── 3. pages ────────────────────────────────────────────────────────────────
const APP_SCRIPTS = ['/assets/js/vendor/supabase.js', '/assets/js/seed-rush-config.js', '/assets/js/seed-rush.js'];

const NOSCRIPT = `<noscript><p class="sr-noscript">Seed Rush needs JavaScript to play. You can still <a href="/verses">read the verses behind the game</a>.</p></noscript>`;

