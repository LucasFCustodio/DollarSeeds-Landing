function modeCards() {
  return MODES.map(([key, name, blanks, options, points]) => `          <li class="sr-mode-card sr-mode-${key}">
            <h3>${name}</h3>
            <p class="sr-mode-facts"><span>${blanks}</span><span>${options}</span></p>
            <p class="sr-mode-points">${points}</p>
          </li>`).join('\n');
}

